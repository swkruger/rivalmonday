// Generates the catalogue seed SQL from the YAML packs. Writes packages/db/src/catalog-seed.sql.ts (used by
// `seedVerticalCatalog`) and prints the migration form (statements separated by drizzle breakpoints) to stdout.
// Output is deterministic (sorted keys, packs in id order) so re-running produces no diff.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { listVerticalPacks, loadVerticalPack, splitPack } from '../src/index';

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (xs: string[]) => (xs.length ? `ARRAY[${xs.map(lit).join(', ')}]::text[]` : `'{}'::text[]`);

function sortKeys(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (v && typeof v === 'object') {
    const entries = Object.entries(v as Record<string, unknown>).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    return Object.fromEntries(entries.map(([k, x]) => [k, sortKeys(x)]));
  }
  return v;
}
const json = (v: unknown) => {
  const text = JSON.stringify(sortKeys(v));
  if (text.includes('$json$')) throw new Error('config contains the $json$ delimiter');
  return `$json$${text}$json$::jsonb`;
};

async function main(): Promise<void> {
  const ids = await listVerticalPacks();
  if (!ids.includes('generic')) throw new Error('packs/generic.yaml is required');
  const verticals: string[] = [];
  const areas: string[] = [];
  const cats: string[] = [];
  const seen = new Set<string>();
  for (const id of ids) {
    const { row, areas: a } = splitPack(await loadVerticalPack(id));
    verticals.push(
      `INSERT INTO vertical (id, name, status, version, gbp_categories, gbp_related_categories, config) VALUES (${lit(row.id)}, ${lit(row.name)}, 'reviewed', ${row.version}, ${arr(row.gbpCategories)}, ${arr(row.gbpRelatedCategories)}, ${json(row.config)}) ON CONFLICT (id) DO NOTHING;`,
    );
    for (const s of a) {
      areas.push(
        `INSERT INTO business_area (vertical_id, id, name, aliases, status) VALUES (${lit(row.id)}, ${lit(s.id)}, ${lit(s.name)}, ${arr(s.aliases)}, 'reviewed') ON CONFLICT (vertical_id, id) DO NOTHING;`,
      );
    }
    if (id === 'generic') continue; // generic gets no vertical_category rows
    for (const [kind, list] of [
      ['primary', row.gbpCategories],
      ['related', row.gbpRelatedCategories],
    ] as const) {
      for (const c of list) {
        const lc = c.trim().toLowerCase();
        if (!lc || seen.has(lc)) continue;
        seen.add(lc);
        cats.push(`INSERT INTO vertical_category (category_lc, vertical_id, kind) VALUES (${lit(lc)}, ${lit(row.id)}, '${kind}') ON CONFLICT (category_lc) DO NOTHING;`);
      }
    }
  }
  const statements = [...verticals, ...areas, ...cats];
  const out = fileURLToPath(new URL('../../db/src/catalog-seed.sql.ts', import.meta.url));
  writeFileSync(
    out,
    `// GENERATED by \`pnpm --filter @cs/verticals seed-sql\` from packages/verticals/packs/*.yaml. Do not edit.\nexport const VERTICAL_CATALOG_SEED: string[] = ${JSON.stringify(statements, null, 2)};\n`,
  );
  process.stdout.write(`${statements.join('\n--> statement-breakpoint\n')}\n`);
}

void main();
